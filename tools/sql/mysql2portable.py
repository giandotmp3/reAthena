#!/usr/bin/env python3
"""Generate the PostgreSQL and SQLite schemas from the upstream MySQL-dialect sql-files.

rAthena no longer runs on MySQL/MariaDB (analysis/rathena/DATABASE_DECISION.md). The upstream
files sql-files/{main,logs,web,roulette_default_data}.sql stay the *source* so that upstream schema
changes keep merging cleanly; this script translates them into

    sql-files/postgresql/<name>.sql
    sql-files/sqlite/<name>.sql

Run it after any change to the source files; CI fails when the generated files are stale:

    python3 tools/sql/mysql2portable.py           # regenerate
    python3 tools/sql/mysql2portable.py --check   # exit 1 if out of date

Translation rules (kept deliberately small; the input is our own controlled DDL):
  * identifiers: backticks -> double quotes; index names are prefixed with the table name
    (index names are per schema in PostgreSQL/SQLite, per table in MySQL)
  * integer types widen where MySQL's unsigned range needs it (int unsigned -> bigint)
  * auto_increment -> PostgreSQL identity (START WITH the table's AUTO_INCREMENT) /
    SQLite INTEGER PRIMARY KEY AUTOINCREMENT seeded through sqlite_sequence
  * enum(...) -> text + CHECK; datetime -> timestamp(0) / ISO text; blob -> bytea / BLOB
  * case-insensitive identity columns (login.userid, char.name, guild.name, party.name) keep the
    MySQL default behaviour: citext on PostgreSQL, COLLATE NOCASE on SQLite
  * ENGINE / CHARSET clauses are dropped; FOREIGN KEY clauses are kept
"""
from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "sql-files"
SOURCES = ["main.sql", "logs.sql", "web.sql", "roulette_default_data.sql"]

# Columns that MySQL compares case-insensitively and the server relies on (unique names,
# lookups by name). Everything else keeps the engine's default (case-sensitive) comparison.
CASE_INSENSITIVE = {("login", "userid"), ("char", "name"), ("guild", "name"), ("party", "name")}

HEADER = """-- GENERATED by tools/sql/mysql2portable.py from sql-files/{src} -- do not edit by hand.
-- Target: {dialect}. Regenerate after changing the source file.
"""

PG_PRELUDE = """-- Shared helpers for the {dialect} schema (idempotent).
CREATE EXTENSION IF NOT EXISTS citext;

-- MySQL-compatible time helpers used by the server's queries. Datetimes are stored as local
-- time (timestamp without time zone); the server sets the session time zone on connect.
CREATE OR REPLACE FUNCTION unix_timestamp() RETURNS bigint
  LANGUAGE sql STABLE AS $$ SELECT CAST(EXTRACT(EPOCH FROM now()) AS bigint) $$;
CREATE OR REPLACE FUNCTION unix_timestamp(t timestamp) RETURNS bigint
  LANGUAGE sql STABLE AS $$ SELECT CAST(EXTRACT(EPOCH FROM CAST(t AS timestamptz)) AS bigint) $$;
CREATE OR REPLACE FUNCTION from_unixtime(s bigint) RETURNS timestamp(0)
  LANGUAGE sql STABLE AS $$ SELECT CAST(to_timestamp(s) AS timestamp(0)) $$;
CREATE OR REPLACE FUNCTION from_unixtime(s text) RETURNS timestamp(0)
  LANGUAGE sql STABLE AS $$ SELECT CAST(to_timestamp(CAST(s AS bigint)) AS timestamp(0)) $$;

"""


@dataclass
class Column:
    name: str
    base: str            # mysql base type, lowercased (int, varchar, enum, ...)
    args: str | None     # "(32)" / "('M','F')" etc.
    unsigned: bool
    not_null: bool
    default: str | None  # raw default token
    auto_increment: bool


@dataclass
class Table:
    name: str
    columns: list[Column] = field(default_factory=list)
    primary_key: list[str] = field(default_factory=list)
    indexes: list[tuple[str, bool, list[str]]] = field(default_factory=list)  # (name, unique, cols)
    foreign_keys: list[str] = field(default_factory=list)
    auto_increment_start: int | None = None


COL_RE = re.compile(
    r"^`(?P<name>[^`]+)`\s+(?P<type>[A-Za-z]+)(?P<args>\([^)]*\))?(?P<rest>.*)$", re.IGNORECASE)


def strip_comments(sql: str) -> str:
    out = []
    for line in sql.splitlines():
        s = line.strip()
        if s.startswith("--") or s.startswith("#"):
            continue
        # trailing "-- comment" after a column or statement (logs.sql, roulette data)
        out.append(re.sub(r"(^|\s)--\s.*$", "", line))
    return "\n".join(out)


def statements(sql: str) -> list[str]:
    body = strip_comments(sql)
    parts, buf, quote = [], [], None
    for ch in body:
        buf.append(ch)
        if quote:
            if ch == quote:
                quote = None
        elif ch in ("'", '"'):
            quote = ch
        elif ch == ";":
            stmt = "".join(buf).strip()
            if stmt.strip(";").strip():
                parts.append(stmt.rstrip(";").strip())
            buf = []
    tail = "".join(buf).strip()
    if tail:
        parts.append(tail)
    return parts


def split_top_level(body: str) -> list[str]:
    items, depth, buf, quote = [], 0, [], None
    for ch in body:
        if quote:
            buf.append(ch)
            if ch == quote:
                quote = None
            continue
        if ch in ("'", '"'):
            quote = ch
        elif ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            items.append("".join(buf).strip())
            buf = []
        else:
            buf.append(ch)
    if "".join(buf).strip():
        items.append("".join(buf).strip())
    return items


def cols_of(spec: str) -> list[str]:
    return [c.strip().strip("`") for c in spec.strip().strip("()").split(",")]


def parse_create(stmt: str) -> Table:
    m = re.match(r"CREATE TABLE IF NOT EXISTS `([^`]+)`\s*\((.*)\)\s*(.*)$", stmt, re.S | re.I)
    if not m:
        raise ValueError(f"unsupported CREATE TABLE: {stmt[:80]}")
    table = Table(m.group(1))
    opts = m.group(3)
    ai = re.search(r"AUTO_INCREMENT\s*=\s*(\d+)", opts, re.I)
    if ai:
        table.auto_increment_start = int(ai.group(1))
    for item in split_top_level(m.group(2)):
        item = " ".join(item.split())
        up = item.upper()
        if up.startswith("PRIMARY KEY"):
            table.primary_key = cols_of(item[item.index("("):])
        elif up.startswith("UNIQUE KEY") or up.startswith("UNIQUE INDEX") or up.startswith("UNIQUE "):
            mm = re.match(r"UNIQUE (?:KEY|INDEX)?\s*`?([^`(\s]*)`?\s*(\(.*\))", item, re.I)
            table.indexes.append((mm.group(1) or "_".join(cols_of(mm.group(2))), True, cols_of(mm.group(2))))
        elif up.startswith("KEY") or up.startswith("INDEX"):
            mm = re.match(r"(?:KEY|INDEX)\s*`?([^`(\s]*)`?\s*(\(.*\))", item, re.I)
            table.indexes.append((mm.group(1) or "_".join(cols_of(mm.group(2))), False, cols_of(mm.group(2))))
        elif up.startswith("FOREIGN KEY"):
            table.foreign_keys.append(item.replace("`", '"'))
        else:
            cm = COL_RE.match(item)
            if not cm:
                raise ValueError(f"{table.name}: cannot parse column '{item}'")
            rest = cm.group("rest")
            dflt = re.search(r"\bdefault\s+('(?:[^']|'')*'|[^\s,]+)", rest, re.I)
            table.columns.append(Column(
                name=cm.group("name"),
                base=cm.group("type").lower(),
                args=cm.group("args"),
                unsigned=bool(re.search(r"\bunsigned\b", rest, re.I)),
                not_null=bool(re.search(r"\bnot\s+null\b", rest, re.I)),
                default=dflt.group(1) if dflt else None,
                auto_increment=bool(re.search(r"\bauto_increment\b", rest, re.I)),
            ))
    return table


INT_TYPES = {"tinyint", "smallint", "mediumint", "int", "integer", "bigint"}


def pg_type(t: Table, c: Column) -> str:
    if c.base in INT_TYPES:
        if c.base == "tinyint":
            return "smallint"
        if c.base == "smallint":
            return "integer" if c.unsigned else "smallint"
        if c.base == "mediumint":
            return "integer"
        if c.base in ("int", "integer"):
            return "bigint" if c.unsigned else "integer"
        return "bigint"
    if c.base == "varchar" or c.base == "char":
        if (t.name, c.name) in CASE_INSENSITIVE:
            return "citext"
        return f"varchar{c.args}"
    if c.base == "enum":
        return "varchar(32)"
    if c.base in ("text", "longtext", "mediumtext", "tinytext"):
        return "text"
    if c.base in ("blob", "longblob", "mediumblob"):
        return "bytea"
    if c.base == "datetime":
        return "timestamp(0)"
    if c.base == "date":
        return "date"
    if c.base == "float":
        return "real"
    if c.base == "double":
        return "double precision"
    raise ValueError(f"{t.name}.{c.name}: unmapped type {c.base}")


def sqlite_type(t: Table, c: Column) -> str:
    if c.base in INT_TYPES:
        return "INTEGER"
    if c.base in ("blob", "longblob", "mediumblob"):
        return "BLOB"
    if c.base in ("float", "double"):
        return "REAL"
    return "TEXT"


def default_sql(c: Column, dialect: str) -> str | None:
    d = c.default
    if d is None:
        return None
    if d.upper() == "NULL":
        return "NULL"
    if d.upper() == "CURRENT_TIMESTAMP":
        return "CURRENT_TIMESTAMP" if dialect == "pg" else "(strftime('%Y-%m-%d %H:%M:%S', 'now', 'localtime'))"
    if d.startswith("'"):
        inner = d[1:-1]
        if c.base in INT_TYPES or c.base in ("float", "double"):
            return inner if re.fullmatch(r"-?\d+(\.\d+)?", inner) else "0"
        return d
    return d


def enum_check(c: Column) -> str | None:
    if c.base != "enum":
        return None
    values = c.args.strip("()")
    return f'CHECK ("{c.name}" IN ({values}))'


def render_table(t: Table, dialect: str) -> str:
    lines = []
    ai_cols = [c for c in t.columns if c.auto_increment]
    pk = list(t.primary_key)
    extra_unique: list[list[str]] = []
    # SQLite only auto-increments a lone INTEGER PRIMARY KEY. MyISAM allowed an auto_increment
    # column inside a composite key (guild); there the column is unique on its own, so it becomes
    # the key and the original composite stays enforced as a UNIQUE constraint.
    sqlite_rowid_col = None
    if dialect == "sqlite" and ai_cols:
        sqlite_rowid_col = ai_cols[0].name
        if pk and pk != [sqlite_rowid_col]:
            extra_unique.append(pk)
        pk = []  # the key is declared inline on the rowid column
    for c in t.columns:
        q = f'"{c.name}"'
        if dialect == "pg":
            typ = pg_type(t, c)
            parts = [q, typ]
            if c.auto_increment:
                start = t.auto_increment_start or 1
                parts.append(f"GENERATED BY DEFAULT AS IDENTITY (START WITH {start})")
        else:
            typ = sqlite_type(t, c)
            parts = [q, typ]
            if c.name == sqlite_rowid_col:
                parts.append("PRIMARY KEY AUTOINCREMENT")
            elif (t.name, c.name) in CASE_INSENSITIVE:
                parts.append("COLLATE NOCASE")
        if c.not_null or c.auto_increment:
            parts.append("NOT NULL")
        d = default_sql(c, dialect)
        if d is not None and not c.auto_increment:
            parts.append(f"DEFAULT {d}")
        chk = enum_check(c)
        if chk:
            parts.append(chk)
        lines.append("  " + " ".join(parts))
    if pk:
        lines.append("  PRIMARY KEY (" + ", ".join(f'"{c}"' for c in pk) + ")")
    for u in extra_unique:
        lines.append("  UNIQUE (" + ", ".join(f'"{c}"' for c in u) + ")")
    for fk in t.foreign_keys:
        lines.append("  " + fk)
    out = f'CREATE TABLE IF NOT EXISTS "{t.name}" (\n' + ",\n".join(lines) + "\n);\n"
    for name, unique, cols in t.indexes:
        idx = f"{t.name}_{name}"
        out += (f'CREATE {"UNIQUE " if unique else ""}INDEX IF NOT EXISTS "{idx}" ON "{t.name}" ('
                + ", ".join(f'"{c}"' for c in cols) + ");\n")
    if dialect == "sqlite" and sqlite_rowid_col and t.auto_increment_start and t.auto_increment_start > 1:
        seq = t.auto_increment_start - 1
        out += (f"INSERT INTO sqlite_sequence (name, seq) SELECT '{t.name}', {seq} "
                f"WHERE NOT EXISTS (SELECT 1 FROM sqlite_sequence WHERE name = '{t.name}');\n")
    return out + "\n"


def render_insert(stmt: str, dialect: str, tables: dict[str, Table]) -> str:
    s = stmt.replace("`", '"')
    m = re.match(r'INSERT INTO "([^"]+)"', s)
    t = tables.get(m.group(1)) if m else None
    # After explicit ids are inserted into a PostgreSQL identity column, move its sequence past
    # them so the next generated id cannot collide.
    if dialect == "pg":
        s = s + " ON CONFLICT DO NOTHING"
    else:
        s = s.replace("INSERT INTO", "INSERT OR IGNORE INTO", 1)
    out = s + ";\n"
    if dialect == "pg" and t is not None:
        for c in t.columns:
            if c.auto_increment:
                out += (f"SELECT setval(pg_get_serial_sequence('\"{t.name}\"', '{c.name}'), "
                        f"GREATEST((SELECT MAX(\"{c.name}\") FROM \"{t.name}\"), {(t.auto_increment_start or 1) - 1}, 1));\n")
    return out


def convert(src_name: str, dialect: str, known: dict[str, Table]) -> str:
    text = (SRC / src_name).read_text(encoding="utf-8")
    label = "PostgreSQL 16+" if dialect == "pg" else "SQLite 3.45+"
    out = HEADER.format(src=src_name, dialect=label)
    if dialect == "pg" and src_name == "main.sql":
        out += PG_PRELUDE.format(dialect=label)
    elif dialect == "sqlite":
        out += "PRAGMA foreign_keys = ON;\n\n"
    for stmt in statements(text):
        head = stmt.lstrip().upper()
        if head.startswith("CREATE TABLE"):
            t = parse_create(stmt)
            known[t.name] = t
            out += render_table(t, dialect)
        elif head.startswith("INSERT"):
            out += render_insert(stmt, dialect, known)
        elif head.startswith(("SET ", "DROP ", "LOCK ", "UNLOCK ")):
            continue
        else:
            raise ValueError(f"{src_name}: unsupported statement: {stmt[:80]}")
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if generated files are out of date")
    args = ap.parse_args()
    stale = []
    for dialect, subdir in (("pg", "postgresql"), ("sqlite", "sqlite")):
        known: dict[str, Table] = {}
        for name in SOURCES:
            content = convert(name, dialect, known)
            target = SRC / subdir / name
            if args.check:
                if not target.exists() or target.read_text(encoding="utf-8") != content:
                    stale.append(str(target.relative_to(ROOT)))
            else:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(content, encoding="utf-8", newline="\n")
    if stale:
        print("out of date (run tools/sql/mysql2portable.py):\n  " + "\n  ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
