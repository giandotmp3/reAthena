#!/usr/bin/env python3
"""Bundles the package's Luau modules into ONE script for the Luau CLI.

The sources reference a global `import(name)` that the mod loader (engine) or tools/run_tests.py (plain Lua) supplies.
The Luau CLI sandboxes every `require`d module, so a global defined by an entry script is invisible to them; the bundle
instead wraps every module in a function and declares `import` as a local above them (lexical scope), which keeps the
sources untouched.

usage: bundle_luau.py <entry> <out.luau> [--lib]
  entry: tests/main | tests/golden_report | tests/bench_weapon | tests/trace_case | (with --lib) any module, e.g. scripts/formulas
  --lib: do not run the entry; leave the local `import` in scope so the caller can append code (tests/adapter.py does)
"""
import pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DIRS = ["scripts", "data", "conformance", "tests"]  # plus build/golden_*.luau (generated data), never earlier bundles


def main():
    entry, out = sys.argv[1], pathlib.Path(sys.argv[2])
    lib = "--lib" in sys.argv
    parts = ["--!nonstrict\n-- GENERATED by tools/bundle_luau.py. Do not edit.\n",
             "local __src, __cache = {}, {}\n",
             "local function import(name)\n\tlocal c = __cache[name]\n\tif c == nil then\n\t\tlocal f = __src[name]\n"
             "\t\tif not f then error('import: unknown module ' .. tostring(name)) end\n\t\tc = f()\n\t\tif c == nil then c = true end\n"
             "\t\t__cache[name] = c\n\tend\n\treturn c\nend\n"]
    n = 0
    dirs = ["scripts", "data"] if lib else DIRS  # a library bundle carries no tests and no golden data
    files = [p for d in dirs for p in sorted((ROOT / d).rglob("*.luau"))] + ([] if lib else sorted((ROOT / "build").glob("golden_*.luau")))
    for p in files:
        name = p.relative_to(ROOT).with_suffix("").as_posix()
        parts.append(f"__src[{name!r}] = function()\n-- {name}\n{p.read_text()}\nend\n")
        n += 1
    if lib:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text("".join(parts))
        print(f"bundle_luau: {n} modules -> {out} (library)")
        return
    call = "()" if entry.endswith(("golden_report", "bench_weapon", "print_rule_cases", "trace_case")) else ""
    parts.append(f"local __code = import({entry!r}){call}\n"
                 "if __code ~= 0 then error('luau run failed: exit code ' .. tostring(__code), 0) end\n")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("".join(parts))
    print(f"bundle_luau: {n} modules -> {out}")


if __name__ == "__main__":
    main()
