#!/usr/bin/env python3
"""Writes data/status_records.luau: the per-status DATA part of the status layer (states, calc flags, flags, options, min rate / duration,
Fail / EndOnStart / EndOnEnd / EndReturn lists, script text), taken from the migrated renewal status database (db/re/status.yml + db/status.yml
through rathena-migrate; BR-RULESET-051). The behaviour part (named val fields, contributions) is hand-written in scripts/status/defs.

usage: gen_status_records.py [<migrated status.luau>] [<out>]
  default input: tooling/migrate/out/renewal/status.luau if present, else the migrator is run into a temporary directory
  (python3 tooling/migrate/rathena_migrate.py --mode renewal --out <dir>).
"""
import pathlib, re, subprocess, sys, tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
REPO = ROOT.parent.parent.parent  # reAthena checkout
MIG = REPO / "modernized/rathena-engine-reimagined/tooling/migrate"
KEEP = ["legacy_sc", "name", "states", "calc_flags", "flags", "opt1", "opt2", "opt3", "options", "min_rate", "min_duration",
        "fail", "end_on_start", "end_on_end", "end_return", "script", "script_lang", "duration_lookup"]
LISTS = {"states", "calc_flags", "flags", "options", "fail", "end_on_start", "end_on_end", "end_return"}
KEYWORDS = {"and", "break", "do", "else", "elseif", "end", "false", "for", "function", "if", "in", "local", "nil", "not", "or", "repeat", "return",
            "then", "true", "until", "while", "continue", "type", "export"}
NS = re.compile(r'^ruleset\.(?:renewal|prerenewal):(?:status|skill)/')


def parse(text):
    entries = {}
    cur = None
    for line in text.split("\n"):
        m = re.match(r'^\t\["ruleset\.[a-z]+:status/([^"]+)"\] = \{$', line)
        if m:
            cur = {}
            entries[m.group(1)] = cur
            continue
        if cur is None:
            continue
        if line == "\t},":
            cur = None
            continue
        m = re.match(r'^\t\t([a-z_0-9]+) = (.*?),?$', line)
        if m:
            k, v = m.groups()
            if v == "{":
                cur[k] = []
            elif v.startswith("{") and v.endswith("}"):
                cur[k] = [NS.sub("", x.strip().strip('"')) for x in v[1:-1].split(",") if x.strip()]
            elif v.startswith('"'):
                cur[k] = bytes(v[1:-1], "utf8").decode("unicode_escape") if "\\" in v else v[1:-1]
            else:
                cur[k] = int(v)
            continue
        m = re.match(r'^\t\t\t"([^"]+)",?$', line)  # multi-line list item
        if m and cur:
            last = [k for k, val in cur.items() if isinstance(val, list)][-1]
            cur[last].append(NS.sub("", m.group(1)))
    return entries


def lua(v):
    if isinstance(v, int):
        return str(v)
    if isinstance(v, list):
        return "{" + ",".join(f'"{x}"' for x in v) + "}"
    s = v.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    return f'"{s}"'


def main():
    src = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else MIG / "out/renewal/status.luau"
    out = pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "data/status_records.luau"
    tmp = None
    if not src.exists():
        tmp = tempfile.TemporaryDirectory()
        subprocess.run([sys.executable, "-I", str(MIG / "rathena_migrate.py"), "--mode", "renewal", "--out", tmp.name], check=True, cwd=REPO,
                       stdout=subprocess.DEVNULL)
        src = pathlib.Path(tmp.name) / "renewal/status.luau"
    entries = parse(src.read_text())
    lines = ["--!nonstrict",
             "-- GENERATED by tools/gen_status_records.py from the migrated renewal status database (rathena-migrate). Do not edit.",
             "-- Per status (key = lower case status name): the data part of BR-RULESET-051. The behaviour part lives in scripts/status/defs.",
             "return {"]
    for key in sorted(entries, key=lambda k: entries[k]["legacy_sc"]):
        e = entries[key]
        assert re.fullmatch(r"[a-z0-9_]+", key), key
        items = [f"{k}={lua(e[k])}" for k in KEEP if k in e and not (k in LISTS and e[k] == [])]
        ident = re.fullmatch(r"[a-z_][a-z0-9_]*", key) and key not in KEYWORDS
        lines.append(f"\t{key if ident else '[\"' + key + '\"]'}={{" + ",".join(items) + "},")
    lines.append("}")
    out.write_text("\n".join(lines) + "\n")
    print(f"{len(entries)} status records -> {out} ({out.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
