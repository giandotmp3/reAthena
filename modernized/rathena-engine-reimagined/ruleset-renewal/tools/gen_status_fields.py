#!/usr/bin/env python3
"""Writes docs/STATUS_FIELDS.md from the status definitions (scripts/status/defs): the names of the val1..val4 slots of every covered status (Q-F of
BR_RULESET.md) and every contribution with its status.cpp line. The Luau registry is dumped by tests/status_dump.luau, so the document cannot drift
from the code (tests/test_ruleset_renewal.py regenerates and compares).

usage: gen_status_fields.py [--luau PATH] [--check]    (--check: exit 1 when docs/STATUS_FIELDS.md differs from what the code says)
"""
import os, pathlib, shutil, subprocess, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DOC = ROOT / "docs" / "STATUS_FIELDS.md"


def luau_exe():
    args = sys.argv[1:]
    p = args[args.index("--luau") + 1] if "--luau" in args else None
    exe = p or os.environ.get("LUAU") or shutil.which("luau")
    if not exe:
        sys.exit("gen_status_fields: Luau CLI not found")
    return exe


def dump():
    out = ROOT / "build" / "bundle_dump.luau"
    subprocess.run([sys.executable, "-I", str(ROOT / "tools" / "bundle_luau.py"), "tests/status_dump", str(out)], check=True, stdout=subprocess.DEVNULL)
    r = subprocess.run([luau_exe(), str(out)], capture_output=True, text=True, cwd=ROOT, check=True)
    return r.stdout.splitlines()


def render(lines):
    statuses, contrib, wheres = [], {}, {}
    for ln in lines:
        p = ln.split("\t")
        if p[0] == "S":
            statuses.append(p[1:])
            contrib[p[1]], wheres[p[1]] = [], []
        elif p[0] == "C":
            contrib[p[1]].append(p[2:])
        elif p[0] == "W":
            wheres[p[1]].append(p[2])
    named = sum(1 for s in statuses if any(x != "-" for x in s[2:6]))
    out = ["# Status val1..val4 fields and contributions (renewal)", "",
           "GENERATED by `tools/gen_status_fields.py` from `scripts/status/defs/*.luau`. Do not edit; edit the definitions and regenerate.", "",
           "Answer to **Q-F** of `analysis/rathena/BR_RULESET.md` for the statuses that the RENEWAL `status_calc_*` functions of `src/map/status.cpp` read: the status database "
           "(`db/re/status.yml`) never names `val1..val4`, the meaning lives in the code. Each definition below names the slots the legacy code reads (and, from "
           "`status_change_start`, how it computes them where that is a one-liner); a slot written `-` is not read by any covered function. A save-format migration is "
           "not needed: the names are an overlay on the same four integers (`status.define` maps `fields = { val1 = \"level\", ... }` to the slot numbers).", "",
           f"{len(statuses)} statuses defined, {named} with at least one named slot, {sum(len(v) for v in contrib.values())} contributions. The contribution column reads "
           "`attribute op value [when condition] @status.cpp line`; the line is also the order key (`at`) in which the contributions of one attribute are applied.", ""]
    for s in statuses:
        name, sc, f1, f2, f3, f4, note = s[0], s[1], s[2], s[3], s[4], s[5], s[6] if len(s) > 6 else ""
        out.append(f"## {name} ({sc})")
        out.append("")
        out.append(f"val1 `{f1}`, val2 `{f2}`, val3 `{f3}`, val4 `{f4}`")
        if note:
            out.append("")
            out.append(f"Note: {note}")
        if contrib[name]:
            out.append("")
            for c in contrib[name]:
                attr, op, value, when, at, group = c
                bits = f"- `{attr}` {op}" + (f" `{value}`" if value else "") + (f" when `{when}`" if when else "") + (f" (group {group})" if group else "") + f" @status.cpp:{at}"
                out.append(bits)
        for w in wheres[name]:
            out.append(f"- conditional state `{w}`")
        out.append("")
    return "\n".join(out)


def main():
    text = render(dump())
    if "--check" in sys.argv:
        if not DOC.exists() or DOC.read_text() != text:
            print("docs/STATUS_FIELDS.md is out of date: run tools/gen_status_fields.py")
            return 1
        return 0
    DOC.write_text(text)
    print(f"{DOC} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
