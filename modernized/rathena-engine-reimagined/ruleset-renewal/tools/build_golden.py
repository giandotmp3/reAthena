#!/usr/bin/env python3
"""Expands conformance/golden/weapon_re.jsonl.gz into a Luau data module under build/ (git-ignored).

The committed golden data is the gzip-compressed JSONL written by conformance/golden_gen/gen_cases.py from the
real legacy code. Luau has no gzip/JSON reader in the Luau CLI, so tests load the expanded table module
`build/golden_weapon_re.luau`. Rebuilt only when the source is newer.

usage: build_golden.py [--force]
"""
import gzip, json, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
import os
SRC = pathlib.Path(os.environ.get("GOLDEN_SRC", ROOT / "conformance" / "golden" / "weapon_re.jsonl.gz"))  # GOLDEN_SRC: ad-hoc fuzz sets
DST = ROOT / "build" / "golden_weapon_re.luau"
MAP_KEYS = {"ignore_res", "add_race", "add_ele", "add_size", "add_class", "ladd_race", "ladd_ele", "ladd_size", "aadd_race", "aadd_ele",
            "aadd_size", "aadd_class", "sub_race", "sub_ele", "sub_size", "sub_class", "sub_defele", "critadd_race"}


def lua(v, key=None):
    if isinstance(v, bool): return "true" if v else "false"
    if isinstance(v, int): return str(v)
    if isinstance(v, str): return json.dumps(v)
    if isinstance(v, list): return "{" + ",".join(lua(x) for x in v) + "}"
    if isinstance(v, dict):
        items = []
        for k in sorted(v):
            val = v[k]
            if key in MAP_KEYS:  # index -> percent maps use numeric keys
                items.append(f"[{int(k)}]={lua(val)}")
            elif k.isidentifier() and k not in ("end", "not", "and", "or", "if", "then", "do", "in", "for", "function", "local", "nil", "repeat", "return", "until", "while", "break", "else", "elseif", "true", "false"):
                items.append(f"{k}={lua(val, k)}")
            else:
                items.append(f"[{json.dumps(k)}]={lua(val, k)}")
        return "{" + ",".join(items) + "}"
    raise TypeError(type(v))


STATUS_SRC = ROOT / "conformance" / "golden" / "status_re.jsonl.gz"
STATUS_DST = ROOT / "build" / "status_golden_re.luau"


def build_status(force):
    """conformance/golden/status_re.jsonl.gz (status_calc_* of the real binary) -> build/status_golden_re.luau: { meta = {...}, cases = {...} }"""
    if not STATUS_SRC.exists():
        return
    if STATUS_DST.exists() and STATUS_DST.stat().st_mtime >= STATUS_SRC.stat().st_mtime and not force:
        return
    parts = ["--!nonstrict\n-- GENERATED by tools/build_golden.py from conformance/golden/status_re.jsonl.gz. Do not edit or commit.\n"]
    n = 0
    with gzip.open(STATUS_SRC, "rt") as f:
        meta = json.loads(f.readline())
        parts.append("return {\nmeta=" + lua(meta, "meta") + ",\ncases={\n")
        for line in f:
            parts.append(lua(json.loads(line)) + ",\n")
            n += 1
    parts.append("}}\n")
    STATUS_DST.parent.mkdir(parents=True, exist_ok=True)
    STATUS_DST.write_text("".join(parts))
    print(f"build_golden: {n} status cases -> {STATUS_DST} ({STATUS_DST.stat().st_size} bytes)")


def main():
    build_status("--force" in sys.argv)
    if not SRC.exists():
        sys.exit(f"missing {SRC}")
    if DST.exists() and DST.stat().st_mtime >= SRC.stat().st_mtime and "--force" not in sys.argv:
        return
    DST.parent.mkdir(parents=True, exist_ok=True)
    parts = ["--!nonstrict\n-- GENERATED by tools/build_golden.py from conformance/golden/weapon_re.jsonl.gz. Do not edit or commit.\nreturn {\n"]
    n = 0
    with gzip.open(SRC, "rt") as f:
        for line in f:
            parts.append(lua(json.loads(line)) + ",\n")
            n += 1
    parts.append("}\n")
    DST.write_text("".join(parts))
    print(f"build_golden: {n} cases -> {DST} ({DST.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
