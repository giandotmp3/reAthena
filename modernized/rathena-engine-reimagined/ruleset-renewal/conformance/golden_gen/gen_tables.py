#!/usr/bin/env python3
"""Generates data/damage_tables.luau (element matrix, size modifiers) for the weapon pipeline.

Source of truth is the legacy YAML (db/re/attr_fix.yml, db/size_fix.yml + db/re/size_fix.yml).
With --dump <file> (written by the golden hook from the REAL server's loaded tables: elemental_attribute_db and size_fix_db)
the generated tables are compared with what the legacy binary actually uses; any difference aborts.

usage: gen_tables.py <repo-root> <out.luau> [--dump dump.txt]
"""
import sys, pathlib, yaml

repo = pathlib.Path(sys.argv[1]); out = pathlib.Path(sys.argv[2])
dump = pathlib.Path(sys.argv[sys.argv.index("--dump") + 1]) if "--dump" in sys.argv else None

ELE = ["Neutral", "Water", "Earth", "Fire", "Wind", "Poison", "Holy", "Dark", "Ghost", "Undead"]
WEAPONS = ["Fist", "Dagger", "1hSword", "2hSword", "1hSpear", "2hSpear", "1hAxe", "2hAxe", "Mace", "2hMace", "Staff", "Bow",
           "Knuckle", "Musical", "Whip", "Book", "Katar", "Revolver", "Rifle", "Gatling", "Shotgun", "Grenade", "Huuma", "2hStaff"]

def load(p): return yaml.safe_load(open(p))

# element matrix: attr[level][atk][def]; the db/re file fully defines the 4 levels
attr = {}
doc = load(repo / "db/re/attr_fix.yml")
for lvl in doc["Body"]:
    L = lvl["Level"]
    attr[L] = [[100] * 10 for _ in range(10)]
    for ai, an in enumerate(ELE):
        row = lvl.get(an) or {}
        for di, dn in enumerate(ELE):
            if dn in row: attr[L][ai][di] = row[dn]

# size modifiers: base file then the db/re import (later entries override the fields they name)
size = {w: [100, 100, 100] for w in range(len(WEAPONS))}
for f in ["db/size_fix.yml", "db/re/size_fix.yml"]:
    for e in load(repo / f)["Body"]:
        w = WEAPONS.index(e["Weapon"])
        for i, k in enumerate(["Small", "Medium", "Large"]):
            if k in e: size[w][i] = e[k]

if dump:
    seen_a, seen_s = 0, 0
    for line in dump.read_text().splitlines():
        t = line.split()
        if t[0] == "attr":
            lv, a, d, r = map(int, t[1:])
            if a < 10 and d < 10:
                assert attr[lv][a][d] == r, f"attr mismatch lv{lv} {a}->{d}: yml {attr[lv][a][d]} legacy {r}"
                seen_a += 1
        elif t[0] == "size":
            w, s, m, l = map(int, t[1:])
            assert size[w] == [s, m, l], f"size mismatch weapon {w}: yml {size[w]} legacy {[s, m, l]}"
            seen_s += 1
    print(f"cross-checked {seen_a} element cells and {seen_s} weapon rows against the legacy binary")
    # the battle.conf defaults the pipeline reads (data/damage_cfg.luau next to the output) against what the binary loaded
    cfg_file = out.parent / "damage_cfg.luau"
    if cfg_file.exists():
        import re
        mine = {k: int(v) for k, v in re.findall(r"(\w+) = (-?\d+)", "\n".join(l.split("--")[0] for l in cfg_file.read_text().splitlines()))}
        seen_c, missing = 0, []
        for line in dump.read_text().splitlines():
            t = line.split()
            if t[0] == "cfg" and t[1] in mine:
                assert mine[t[1]] == int(t[2]), f"cfg mismatch {t[1]}: damage_cfg.luau {mine[t[1]]} legacy {t[2]}"
                seen_c += 1
        names = {line.split()[1] for line in dump.read_text().splitlines() if line.split()[0] == "cfg"}
        missing = sorted(k for k in mine if k not in names)
        print(f"cross-checked {seen_c} battle config values against the legacy binary; not dumped (not checked): {', '.join(missing) or 'none'}")

L = ["--!nonstrict",
     "-- GENERATED by conformance/golden_gen/gen_tables.py from db/re (attr_fix.yml, size_fix.yml). Do not edit.",
     "-- element_pct[level][atk_element][def_element] (0-based element ids: Neutral Water Earth Fire Wind Poison Holy Dark Ghost Undead)",
     "-- size_pct[weapon_type] = { small, medium, large } (percent, indexed by size 0..2 -> [size + 1])",
     "return {", "\telement_pct = {"]
for lv in sorted(attr):
    L.append(f"\t\t[{lv}] = {{")
    for a in range(10):
        L.append(f"\t\t\t[{a}] = {{" + ", ".join(f"[{d}] = {attr[lv][a][d]}" for d in range(10)) + "},")
    L.append("\t\t},")
L.append("\t},")
L.append("\tsize_pct = {")
for w in range(len(WEAPONS)):
    L.append(f"\t\t[{w}] = {{ {size[w][0]}, {size[w][1]}, {size[w][2]} }}, -- {WEAPONS[w]}")
L.append("\t},")
L.append("}")
out.write_text("\n".join(L) + "\n")
print("wrote", out)
