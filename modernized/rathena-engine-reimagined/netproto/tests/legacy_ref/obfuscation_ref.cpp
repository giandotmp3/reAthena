// Reference harness for the legacy packet-id obfuscation (BR-MAP-059 / CAP-24).
//
// The key schedule below is copied from rAthena src/map/clif.cpp (clif_parse and
// clif_parse_WantToConnection), Copyright (c) rAthena Dev Teams, licensed under GNU GPL, see LICENCE in
// the legacy tree. Only the arithmetic is kept; the socket plumbing around it is not. It is compiled
// into a tiny executable (netproto_obf_ref) so the expected vectors in obf_vectors.inc come from the
// legacy routine itself, not from a re-implementation in the code under test.
//
// The key words are FAKE test values taken from the command line below; no client key is stored here.
//
//   netproto_obf_ref            prints obf_vectors.inc
//   netproto_obf_ref --check F  exits 1 unless F equals what it would print
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <fstream>
#include <sstream>
#include <string>
#include <vector>

typedef uint32_t uint32;
typedef int32_t int32;

namespace {

// ---- copied logic -------------------------------------------------------------------------------
uint32 clif_cryptKey[3];  // static uint32 clif_cryptKey[] = { a, b, c }; (clif_obfuscation.hpp)

struct session_data { uint32 cryptKey; };

// clif_parse: the packet id as the server recovers it. `sd` is null until the connect packet created it.
int32 legacy_parse_cmd(int32 cmd, session_data* sd) {
  if (sd) {
    // Decrypt the current packet ID with the last key stored in the session.
    cmd = (cmd ^ ((sd->cryptKey >> 16) & 0x7FFF));
  } else {
    // A player tries to connect - use the initial keys for the decryption of the packet ID.
    cmd = (cmd ^ ((((clif_cryptKey[0] * clif_cryptKey[1]) + clif_cryptKey[2]) >> 16) & 0x7FFF));
  }
  return cmd;
}

// clif_parse, after a valid frame: "Update key for the next packet"
void legacy_after_packet(session_data* sd) {
  if (sd) sd->cryptKey = ((sd->cryptKey * clif_cryptKey[1]) + clif_cryptKey[2]) & 0xFFFFFFFF;
}

// clif_parse_WantToConnection: session creation
void legacy_create_session(session_data* sd) {
  sd->cryptKey = (((((clif_cryptKey[0] * clif_cryptKey[1]) + clif_cryptKey[2]) & 0xFFFFFFFF) * clif_cryptKey[1]) + clif_cryptKey[2]) & 0xFFFFFFFF;
}
// ---- end of copied logic ------------------------------------------------------------------------

struct KeySet { uint32 k[3]; };
const KeySet kSets[] = {
    {{0x1A2B3C4Du, 0x00010001u, 0x0000BEEFu}},
    {{0x11111111u, 0x22222222u, 0x33333333u}},
    {{0xDEADBEEFu, 0x0BADF00Du, 0x00C0FFEEu}},
    {{1u, 2u, 3u}},  // degenerate: the mask stays 0 for 16 packets; kept as a vector, not as a recommendation
};

std::string render() {
  std::ostringstream o;
  o << "// GENERATED by tests/legacy_ref/obfuscation_ref.cpp (the legacy schedule, FAKE keys). DO NOT EDIT.\n";
  uint32 lcg = 12345;
  for (const KeySet& ks : kSets) {
    std::memcpy(clif_cryptKey, ks.k, sizeof clif_cryptKey);
    o << "{ {0x" << std::hex << ks.k[0] << "u, 0x" << ks.k[1] << "u, 0x" << ks.k[2] << "u}, {\n";
    session_data sd;
    session_data* cur = nullptr;  // no session yet: the first packet is the connect packet
    for (int i = 0; i < 40; ++i) {
      lcg = lcg * 1103515245u + 12345u;
      const int32 plain = static_cast<int32>((lcg >> 8) & 0x7FFF);
      // client side of the same schedule: wire = plain ^ mask (xor is its own inverse)
      const int32 wire = legacy_parse_cmd(plain, cur);
      // server side: recovering the plain id from the wire id
      const int32 back = legacy_parse_cmd(wire, cur);
      if (back != plain) { std::fprintf(stderr, "legacy xor is not an involution?\n"); std::exit(2); }
      o << "  {0x" << std::hex << plain << ", 0x" << wire << "},\n";
      if (!cur) {
        legacy_create_session(&sd);  // the connect packet created the session
        cur = &sd;
      } else {
        legacy_after_packet(cur);
      }
    }
    o << "} },\n";
  }
  return o.str();
}

}  // namespace

int main(int argc, char** argv) {
  const std::string out = render();
  if (argc == 3 && std::strcmp(argv[1], "--check") == 0) {
    std::ifstream f(argv[2]);
    std::ostringstream have;
    have << f.rdbuf();
    if (have.str() != out) { std::fprintf(stderr, "%s differs from the legacy routine's output\n", argv[2]); return 1; }
    return 0;
  }
  std::fputs(out.c_str(), stdout);
  return 0;
}
