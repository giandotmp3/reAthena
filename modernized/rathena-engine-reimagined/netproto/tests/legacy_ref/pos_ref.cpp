// Reference harness for the packed position sub-encodings (pos3 / pos6).
// WBUFPOS, WBUFPOS2, RBUFPOS and RBUFPOS2 are copied from rAthena src/map/clif.cpp (Copyright (c) rAthena
// Dev Teams, licensed under GNU GPL, see LICENCE in the legacy tree). Run: netproto_pos_ref [--check FILE].
#include <cstdint>
#include <cstdio>
#include <cstring>
#include <fstream>
#include <sstream>
#include <string>

typedef uint8_t uint8;
typedef int16_t int16;
typedef uint16_t uint16;
typedef int32_t int32;

// ---- copied logic -----------------------------------------------------------------------------------
static inline void WBUFPOS(uint8* p, uint16 pos, int16 x, int16 y, unsigned char dir) {
	p += pos;
	p[0] = (uint8)(x>>2);
	p[1] = (uint8)((x<<6) | ((y>>4)&0x3f));
	p[2] = (uint8)((y<<4) | (dir&0xf));
}

// client-side: x0+=sx0*0.0625-0.5 and y0+=sy0*0.0625-0.5
static inline void WBUFPOS2(uint8* p, uint16 pos, int16 x0, int16 y0, int16 x1, int16 y1, uint8 sx0, uint8 sy0) {
	p += pos;
	p[0] = (uint8)(x0>>2);
	p[1] = (uint8)((x0<<6) | ((y0>>4)&0x3f));
	p[2] = (uint8)((y0<<4) | ((x1>>6)&0x0f));
	p[3] = (uint8)((x1<<2) | ((y1>>8)&0x03));
	p[4] = (uint8)y1;
	p[5] = (uint8)((sx0<<4) | (sy0&0x0f));
}

static inline void RBUFPOS(const uint8* p, uint16 pos, int16* x, int16* y, unsigned char* dir) {
	p += pos;
	if( x ) { x[0] = ( ( p[0] & 0xff ) << 2 ) | ( p[1] >> 6 ); }
	if( y ) { y[0] = ( ( p[1] & 0x3f ) << 4 ) | ( p[2] >> 4 ); }
	if( dir ) { dir[0] = ( p[2] & 0x0f ); }
}

static inline void RBUFPOS2(const uint8* p, uint16 pos, int16* x0, int16* y0, int16* x1, int16* y1, unsigned char* sx0, unsigned char* sy0) {
	p += pos;
	if( x0 ) { x0[0] = ( ( p[0] & 0xff ) << 2 ) | ( p[1] >> 6 ); }
	if( y0 ) { y0[0] = ( ( p[1] & 0x3f ) << 4 ) | ( p[2] >> 4 ); }
	if( x1 ) { x1[0] = ( ( p[2] & 0x0f ) << 6 ) | ( p[3] >> 2 ); }
	if( y1 ) { y1[0] = ( ( p[3] & 0x03 ) << 8 ) | ( p[4] >> 0 ); }
	if( sx0 ) { sx0[0] = ( p[5] & 0xf0 ) >> 4; }
	if( sy0 ) { sy0[0] = ( p[5] & 0x0f ) >> 0; }
}
// ---- end of copied logic ----------------------------------------------------------------------------

static std::string render() {
  std::ostringstream o;
  o << "// GENERATED by tests/legacy_ref/pos_ref.cpp (WBUFPOS/WBUFPOS2/RBUFPOS/RBUFPOS2 of clif.cpp). DO NOT EDIT.\n";
  o << "// POS3(x, y, dir, wire bytes x3, then x y dir as RBUFPOS reads them back); POS6 likewise with RBUFPOS2.\n";
  uint32_t s = 7;
  auto rnd = [&](uint32_t m) { s = s * 1664525u + 1013904223u; return (s >> 8) % m; };
  for (int i = 0; i < 120; ++i) {
    int16 x = (int16)(i < 4 ? (i * 341) : rnd(1024)), y = (int16)(i < 4 ? 1023 - i : rnd(1024)); unsigned char d = (unsigned char)rnd(16);
    uint8 b[3]; WBUFPOS(b, 0, x, y, d);
    int16 rx, ry; unsigned char rd; RBUFPOS(b, 0, &rx, &ry, &rd);
    o << "POS3(" << x << ", " << y << ", " << (int)d << ", " << (int)b[0] << ", " << (int)b[1] << ", " << (int)b[2] << ", "
      << rx << ", " << ry << ", " << (int)rd << ")\n";
  }
  for (int i = 0; i < 120; ++i) {
    int16 a[4] = {(int16)rnd(1024), (int16)rnd(1024), (int16)rnd(1024), (int16)rnd(1024)};
    unsigned char sx = (unsigned char)rnd(16), sy = (unsigned char)rnd(16);
    uint8 b[6]; WBUFPOS2(b, 0, a[0], a[1], a[2], a[3], sx, sy);
    int16 r[4]; unsigned char rsx, rsy; RBUFPOS2(b, 0, &r[0], &r[1], &r[2], &r[3], &rsx, &rsy);
    o << "POS6(" << a[0] << ", " << a[1] << ", " << a[2] << ", " << a[3] << ", " << (int)sx << ", " << (int)sy << ", ";
    for (int k = 0; k < 6; ++k) o << (int)b[k] << ", ";
    o << r[0] << ", " << r[1] << ", " << r[2] << ", " << r[3] << ", " << (int)rsx << ", " << (int)rsy << ")\n";
  }
  return o.str();
}

int main(int argc, char** argv) {
  const std::string out = render();
  if (argc == 3 && std::strcmp(argv[1], "--check") == 0) {
    std::ifstream f(argv[2]);
    std::ostringstream have;
    have << f.rdbuf();
    if (have.str() != out) { std::fprintf(stderr, "%s differs from the legacy routine's output\n", argv[2]); return 1; }
    return 0;
  }
  std::fputs(out.c_str(), stdout);
  return 0;
}
