#!/usr/bin/env python3
"""Expands conformance/golden/*.jsonl.gz into Luau data modules under build/ (git-ignored).

The committed golden data is the gzip-compressed JSONL written by conformance/golden_gen/gen_cases.py from the
real legacy code. Luau has no gzip/JSON reader in the Luau CLI, so tests load the expanded table module
`build/golden_weapon_pre.luau`. Rebuilt only when the source is newer.

usage: build_golden.py [--force]
"""
import gzip, json, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
import os
SRC = pathlib.Path(os.environ.get("GOLDEN_SRC", ROOT / "conformance" / "golden" / "weapon_pre.jsonl.gz"))  # GOLDEN_SRC: ad-hoc fuzz sets
DST = ROOT / "build" / "golden_weapon_pre.luau"
MAP_KEYS = {"add_race", "add_ele", "add_size", "add_class", "ladd_race", "ladd_ele", "ladd_size", "aadd_race", "aadd_ele",
            "aadd_size", "aadd_class", "sub_race", "sub_ele", "sub_size", "sub_class", "sub_defele", "critadd_race"}


def lua(v, key=None):
    if isinstance(v, bool): return "true" if v else "false"
    if isinstance(v, int): return str(v)
    if isinstance(v, str): return json.dumps(v)
    if isinstance(v, list): return "{" + ",".join(lua(x) for x in v) + "}"
    if isinstance(v, dict):
        items = []
        for k in sorted(v):
            val = v[k]
            if key in MAP_KEYS:  # index -> percent maps use numeric keys
                items.append(f"[{int(k)}]={lua(val)}")
            elif k.isidentifier() and k not in ("end", "not", "and", "or", "if", "then", "do", "in", "for", "function", "local", "nil", "repeat", "return", "until", "while", "break", "else", "elseif", "true", "false"):
                items.append(f"{k}={lua(val, k)}")
            else:
                items.append(f"[{json.dumps(k)}]={lua(val, k)}")
        return "{" + ",".join(items) + "}"
    raise TypeError(type(v))


def build_vectors():
    """conformance/golden/mapvectors/*.jsonl (map-rules DEF captures) -> build/golden_defense_vectors.luau"""
    d = ROOT / "conformance" / "golden" / "mapvectors"
    dst = ROOT / "build" / "golden_defense_vectors.luau"
    rows = {}
    for kind in ("pc", "mob"):
        rows[kind] = [json.loads(l) for l in (d / f"defense_{kind}_pre_re.jsonl").read_text().splitlines() if l.strip()]
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text("--!nonstrict\n-- GENERATED by tools/build_golden.py. Do not edit or commit.\nreturn " + lua(rows) + "\n")


def build_status():
    """conformance/golden/status_pre.jsonl.gz (status calculation, golden_gen/gen_status_cases.py) -> build/golden_status_pre.luau
    = { consts = {K, skdb, sc}, db = {NAME -> status database record of the real loader}, cases = {...} }"""
    src = pathlib.Path(os.environ.get("GOLDEN_STATUS_SRC", ROOT / "conformance" / "golden" / "status_pre.jsonl.gz"))
    dst = ROOT / "build" / "golden_status_pre.luau"
    if not src.exists():
        return
    if dst.exists() and dst.stat().st_mtime >= src.stat().st_mtime and "--force" not in sys.argv:
        return
    consts, db, cases = None, {}, []
    with gzip.open(src, "rt") as f:
        for line in f:
            r = json.loads(line)
            t = r.pop("t")
            if t == "consts": consts = r
            elif t == "db": db[r["name"]] = r
            else: cases.append(r)
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text("--!nonstrict\n-- GENERATED by tools/build_golden.py from conformance/golden/status_pre.jsonl.gz. Do not edit or commit.\nreturn "
                   + lua({"consts": consts, "db": db, "cases": cases}) + "\n")
    print(f"build_golden: status {len(cases)} cases, {len(db)} db records -> {dst} ({dst.stat().st_size} bytes)")


def main():
    build_vectors()
    build_status()
    if not SRC.exists():
        sys.exit(f"missing {SRC}")
    if DST.exists() and DST.stat().st_mtime >= SRC.stat().st_mtime and "--force" not in sys.argv:
        return
    DST.parent.mkdir(parents=True, exist_ok=True)
    parts = ["--!nonstrict\n-- GENERATED by tools/build_golden.py from conformance/golden/weapon_pre.jsonl.gz. Do not edit or commit.\nreturn {\n"]
    n = 0
    with gzip.open(SRC, "rt") as f:
        for line in f:
            parts.append(lua(json.loads(line)) + ",\n")
            n += 1
    parts.append("}\n")
    DST.write_text("".join(parts))
    print(f"build_golden: {n} cases -> {DST} ({DST.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
