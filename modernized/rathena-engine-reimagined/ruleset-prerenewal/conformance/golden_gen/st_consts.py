#!/usr/bin/env python3
"""Turns the constants dump of the golden hook (RA_GOLDEN_ST_CONSTS) into scripts/status/consts.luau.

usage: st_consts.py DUMP.txt OUT.luau
The Luau file is committed; tests/acceptance/status_golden_test.luau compares it with the golden file's `consts` record, and
`gen_status_cases.py` re-dumps it, so a drift between the legacy tree and the Luau constants is caught.
"""
import sys, pathlib
dump = pathlib.Path(sys.argv[1]).read_text().split("\n")
K, SKDB, SC, CFG, SK = {}, {}, {}, {}, {}
for l in dump:
    p = l.split()
    if len(p) == 2 and p[0] != "MIN_ASPD_VALUE":
        K[p[0]] = int(p[1])
    elif len(p) == 3 and p[0] == "SKDB":
        SKDB[p[1]] = int(p[2])
    elif len(p) == 3 and p[0] == "SC":
        SC[p[1]] = int(p[2])
    elif len(p) == 3 and p[0] == "SCRIPTK" and p[2] != "?":
        SK[p[1]] = int(p[2])
    elif len(p) == 3 and p[0] == "CFG":
        CFG[p[1]] = int(p[2])
out = ["--!nonstrict",
       "-- GENERATED by conformance/golden_gen/st_consts.py from the constants the legacy PRE build reports (RA_GOLDEN_ST_CONSTS). Do not edit.",
       "-- K.<NAME>: the enum / macro values the status code compares with (BL_*, ELE_*, OPTION_*, W_*, ...);",
       "-- K.SKILL_IN_PRE_DB[name]: pc_checkskill() returns 0 for skills that are not in db/pre-re/skill_db.yml;",
       "-- K.SC[name]: the numeric sc_type of each status of the PRE build.",
       "return {"]
for k in sorted(K):
    out.append(f"\t{k} = {K[k]},")
out.append("\tSKILL_IN_PRE_DB = {")
for k in sorted(SKDB):
    out.append(f"\t\t{k} = {'true' if SKDB[k] else 'false'},")
out.append("\t},")
out.append("\t-- battle.conf values the status code reads (defaults of the PRE build; a case may override them)")
out.append("\tCFG = {")
for k in sorted(CFG):
    out.append(f"\t\t{k} = {CFG[k]},")
out.append("\t},")
out.append("\t-- numeric values of the script constants the status scripts use (bonus types, Ele_*, RC_*, Eff_* ...)")
out.append("\tSCRIPT = {")
for k in sorted(SK):
    out.append(f"\t\t{k} = {SK[k]},")
out.append("\t},")
out.append("\tSC = {")
items = sorted(SC.items(), key=lambda kv: kv[1])
line = "\t\t"
for k, v in items:
    key = k if k.isidentifier() else f'["{k}"]'
    tok = f"{key} = {v}, "
    if len(line) + len(tok) > 150:
        out.append(line.rstrip()); line = "\t\t"
    line += tok
out.append(line.rstrip())
out.append("\t},")
out.append("}")
pathlib.Path(sys.argv[2]).write_text("\n".join(out) + "\n")
