#!/usr/bin/env python3
"""Converts the migrated status database (rathena-migrate, mode prerenewal: status.luau) into the compact data/status_records.luau.

usage: st_records.py <path/to/prerenewal/status.luau> <out/data/status_records.luau>
(regenerate the input with: python3 tooling/migrate/rathena_migrate.py migrate --mode prerenewal --only status --out <dir>)
One record per status, keyed by the legacy SC_ suffix (db name): id, sc number, client id / icon, default-duration skill, states, calc flags,
opt1/2/3/options, flags, min rate / duration, the four lists, script text. Lists hold SC names. The records are cross-checked against the
status database the REAL loader holds (golden_status_hook.inc dump, stored in conformance/golden/status_pre.jsonl.gz) by
tests/acceptance/status_golden_test.luau.
"""
import re, sys, pathlib

src = pathlib.Path(sys.argv[1]).read_text()


class L:
    def __init__(self, s): self.s, self.i = s, 0

    def ws(self):
        while True:
            m = re.compile(r"\s+|--[^\n]*").match(self.s, self.i)
            if not m: return
            self.i = m.end()

    def value(self):
        self.ws()
        c = self.s[self.i]
        if c == "{":
            self.i += 1
            items, arr = {}, []
            while True:
                self.ws()
                if self.s[self.i] == "}":
                    self.i += 1
                    return items if items else arr
                m = re.compile(r'(\[\s*"([^"]+)"\s*\]|([A-Za-z_]\w*))\s*=').match(self.s, self.i)
                if m:
                    self.i = m.end()
                    items[m.group(2) or m.group(3)] = self.value()
                else:
                    arr.append(self.value())
                self.ws()
                if self.s[self.i] == ",": self.i += 1
        if c == '"':
            j = self.i + 1
            out = []
            while self.s[j] != '"':
                if self.s[j] == "\\":
                    nxt = self.s[j + 1]
                    out.append({"n": "\n", "t": "\t", '"': '"', "\\": "\\", "r": "\r"}.get(nxt, nxt)); j += 2
                else:
                    out.append(self.s[j]); j += 1
            self.i = j + 1
            return "".join(out)
        m = re.compile(r"-?\d+(\.\d+)?").match(self.s, self.i)
        if m:
            self.i = m.end(); return int(m.group(0)) if "." not in m.group(0) else float(m.group(0))
        for kw, v in (("true", True), ("false", False), ("nil", None)):
            if self.s.startswith(kw, self.i): self.i += len(kw); return v
        raise SyntaxError(self.s[self.i:self.i + 40])


i = src.index("return")
db = L(src[i + len("return"):]).value()
recs = sorted(db.values(), key=lambda r: r["legacy_sc"])


ID2NAME = {r["id"]: r["name"] for r in recs}   # (the migrated ids drop the leading underscore of the db names: status/invisibility is _INVISIBILITY)


def nm(x): return ID2NAME[x]


def lua(v):
    if isinstance(v, bool): return "true" if v else "false"
    if isinstance(v, int): return str(v)
    if isinstance(v, str): return '"' + v.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t") + '"'
    if isinstance(v, list): return "{" + ",".join(lua(x) for x in v) + "}"
    raise TypeError(v)


out = ["--!nonstrict",
       "-- GENERATED by conformance/golden_gen/st_records.py from tooling/migrate/out/prerenewal/status.luau (rathena-migrate, db/pre-re/status.yml).",
       "-- Do not edit. The status record of BR-RULESET-051, keyed by the legacy SC_ suffix; lists hold SC names. Cross-checked against the status",
       "-- database of the real legacy loader by tests/acceptance/status_golden_test.luau.",
       "return {"]
for r in recs:
    f = [f'id = {lua(r["id"])}', f'sc = {r["legacy_sc"]}']
    for k in ("client_id", "icon"):
        if k in r: f.append(f"{k} = {lua(r[k])}")
    if "duration_lookup" in r: f.append(f'duration_skill = {lua(r["duration_lookup"].rsplit("/", 1)[1])}')
    for k, dst in (("states", "states"), ("calc_flags", "calc"), ("flags", "flags")):
        if r.get(k): f.append(f"{dst} = {lua(r[k])}")
    for k in ("opt1", "opt2", "opt3", "options"):
        if r.get(k) is not None: f.append(f"{k} = {lua(r[k])}")
    f.append(f'min_rate = {r.get("min_rate", 0)}')
    f.append(f'min_duration = {r.get("min_duration", 1)}')
    for k in ("fail", "end_on_start", "end_return", "end_on_end"):
        if r.get(k): f.append(f"{k} = {lua([nm(x) for x in r[k]])}")
    if r.get("script"): f.append(f'script = {lua(r["script"])}')
    out.append(f'\t[{lua(r["name"])}] = {{ ' + ", ".join(f) + " },")
out.append("}")
pathlib.Path(sys.argv[2]).write_text("\n".join(out) + "\n")
print(f"{len(recs)} status records")
