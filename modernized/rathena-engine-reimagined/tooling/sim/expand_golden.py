#!/usr/bin/env python3
"""Expands a ruleset package's recorded golden data into Luau modules, WITHOUT writing inside the package.

usage: python3 -I expand_golden.py <package dir> <output dir>

rathena-sim stages golden_weapon_<pre|re>.luau (and, for the pre-renewal package, golden_defense_vectors.luau)
into the bundle of the ruleset mod. The packages expand their gzip-compressed JSONL into a git-ignored build/
directory with their own tools/build_golden.py; when that expansion is missing (a clean checkout) this script
produces the same files in the sim's work directory, reusing the package's own `lua()` converter so the output
is byte-for-byte what the package's tool writes. Nothing is read from the network and nothing in <package dir>
is modified.
"""
import sys

sys.dont_write_bytecode = True  # importing the package's tool must not leave a __pycache__ inside the package

import gzip  # noqa: E402
import importlib.util  # noqa: E402
import json  # noqa: E402
import pathlib  # noqa: E402


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    pkg = pathlib.Path(sys.argv[1]).resolve()
    out = pathlib.Path(sys.argv[2])
    tool = pkg / "tools" / "build_golden.py"
    if not tool.is_file():
        print(f"expand_golden: {tool} not found", file=sys.stderr)
        return 1
    spec = importlib.util.spec_from_file_location("package_build_golden", tool)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    out.mkdir(parents=True, exist_ok=True)
    made = 0
    for src in sorted((pkg / "conformance" / "golden").glob("weapon_*.jsonl.gz")):
        suffix = src.name[len("weapon_"):-len(".jsonl.gz")]
        dst = out / f"golden_weapon_{suffix}.luau"
        parts = [f"--!nonstrict\n-- GENERATED by tools/build_golden.py from conformance/golden/{src.name}. Do not edit or commit.\nreturn {{\n"]
        with gzip.open(src, "rt") as f:
            for line in f:
                parts.append(mod.lua(json.loads(line)) + ",\n")
        parts.append("}\n")
        dst.write_text("".join(parts))
        made += 1
    vec = pkg / "conformance" / "golden" / "mapvectors"
    if vec.is_dir():
        rows = {}
        for kind in ("pc", "mob"):
            f = vec / f"defense_{kind}_pre_re.jsonl"
            if f.is_file():
                rows[kind] = [json.loads(l) for l in f.read_text().splitlines() if l.strip()]
        if rows:
            (out / "golden_defense_vectors.luau").write_text(
                "--!nonstrict\n-- GENERATED by tools/build_golden.py. Do not edit or commit.\nreturn " + mod.lua(rows) + "\n")
            made += 1
    if made == 0:
        print(f"expand_golden: no golden data under {pkg}/conformance/golden", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
