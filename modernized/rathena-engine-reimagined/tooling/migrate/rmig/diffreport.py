"""pre-renewal vs renewal diff report: per DB, entries added/removed/changed and per-field change counts, plus a
'shared-by-diff' summary for the rathena.base vs ruleset.* decision (architecture 6.3)."""
import hashlib


def _fp(v):
    return v


def keyed(db, loaded):
    d = loaded.dbs[db]
    if db == "refine":
        return d.flat()
    return d.rows


def _norm(db, row, loaded):
    """Row -> mode-neutral form: loader representation differences (a field that exists in one build only, ITEMJ_ALL's
    value, monster ATK rewritten by renewal) must not show up as data differences."""
    r = dict(row)
    c = loaded.w.c
    if db == "item_db":
        if r.get("matk") == 0:
            r.pop("matk")
        if r["class_upper"] == c.lim("ITEMJ_ALL"):
            r["class_upper"] = "ALL"
    elif db == "mob_db":
        r["attack"] = r.get("_attack", r["atk"])
        r["attack2"] = r["matk"] if "matk" in r else r["atk2"]
        for k in ("atk", "atk2", "matk"):
            r.pop(k, None)
    for k in list(r):
        if k.startswith("_"):
            del r[k]
    return r


def diff_db(db, pre, ren):
    a, b = keyed(db, pre), keyed(db, ren)
    ka, kb = set(a), set(b)
    common = sorted(ka & kb, key=str)
    added = sorted(kb - ka, key=str)
    removed = sorted(ka - kb, key=str)
    fields = {}
    changed = 0
    identical = 0
    only_fields_pre, only_fields_ren = set(), set()
    for k in common:
        ra, rb = _norm(db, a[k], pre), _norm(db, b[k], ren)
        diffs = [f for f in set(ra) | set(rb) if ra.get(f, "<absent>") != rb.get(f, "<absent>")]
        for f in set(ra) - set(rb):
            only_fields_pre.add(f)
        for f in set(rb) - set(ra):
            only_fields_ren.add(f)
        if diffs:
            changed += 1
            for f in diffs:
                fields[f] = fields.get(f, 0) + 1
        else:
            identical += 1
    return {"db": db, "pre": len(a), "re": len(b), "common": len(common), "added_in_re": len(added),
            "removed_in_re": len(removed), "changed": changed, "identical": identical, "fields": fields,
            "only_fields_pre": sorted(only_fields_pre), "only_fields_re": sorted(only_fields_ren),
            "added_examples": [str(x) for x in added[:5]], "removed_examples": [str(x) for x in removed[:5]]}


DBS = ["item_db", "mob_db", "skill_db", "status", "job_stats", "size_fix", "attr_fix", "refine", "statpoint"]


def build(pre, ren, raw_dbs=()):
    rows = [diff_db(db, pre, ren) for db in DBS]
    rows += [diff_db(db, pre, ren) for db in raw_dbs if db in pre.dbs and db in ren.dbs]
    return rows


def render(rows, meta):
    L = []
    L.append("# Pre-renewal vs renewal data diff")
    L.append("")
    L.append("Generated by `rathena-migrate` (%s). Source: `db/pre-re` + `db/re` resolved with the legacy merge, no `db/import` overlay." % meta.get("version", ""))
    L.append("")
    L.append("Entries are matched by their legacy key (item id, mob id, skill id, SC id, job id, weapon, element level, "
             "refine group/level, base level). \"changed\" = same key, at least one field differs. A DB whose common entries "
             "are all identical is a candidate for `rathena.base`; a DB that differs in most entries or in most fields "
             "stays in the two rulesets (BR-RULESET-079: skills are separate data sets).")
    L.append("")
    L.append("## Summary")
    L.append("")
    L.append("| DB | pre-re | re | common | only in re (added) | only in pre-re (removed) | common identical | common changed | identical % of common |")
    L.append("|---|---:|---:|---:|---:|---:|---:|---:|---:|")
    for r in rows:
        pct = (100.0 * r["identical"] / r["common"]) if r["common"] else 0.0
        L.append("| %s | %d | %d | %d | %d | %d | %d | %d | %.1f |" % (r["db"], r["pre"], r["re"], r["common"], r["added_in_re"],
                                                                    r["removed_in_re"], r["identical"], r["changed"], pct))
    L.append("")
    L.append("## Shared-by-diff decision input")
    L.append("")
    L.append("| DB | verdict | reason |")
    L.append("|---|---|---|")
    for r in rows:
        if r["common"] == 0:
            v, why = "ruleset-specific", "no common keys"
        elif r["added_in_re"] == 0 and r["removed_in_re"] == 0 and r["changed"] == 0:
            v, why = "shared (rathena.base candidate)", "identical in both modes"
        elif r["identical"] / float(r["common"]) >= 0.95 and r["added_in_re"] + r["removed_in_re"] <= 0.05 * max(r["pre"], r["re"]):
            v, why = "mostly shared", "%.1f%% of common entries identical; overlay the %d changed + %d added/removed in the rulesets" % (
                100.0 * r["identical"] / r["common"], r["changed"], r["added_in_re"] + r["removed_in_re"])
        else:
            v, why = "ruleset-specific", "%.1f%% of common entries identical, %d only in re, %d only in pre-re" % (
                100.0 * r["identical"] / r["common"], r["added_in_re"], r["removed_in_re"])
        L.append("| %s | %s | %s |" % (r["db"], v, why))
    L.append("")
    L.append("## Per-field changes (entries whose value differs, among common keys)")
    for r in rows:
        L.append("")
        L.append("### %s" % r["db"])
        L.append("")
        if r["only_fields_pre"] or r["only_fields_re"]:
            L.append("Fields only stored in pre-re rows: %s; only in re rows: %s (mode-dependent loader fields)." % (
                ", ".join(r["only_fields_pre"]) or "-", ", ".join(r["only_fields_re"]) or "-"))
            L.append("")
        if r["added_examples"]:
            L.append("Added in re (first keys): %s" % ", ".join(r["added_examples"]))
            L.append("")
        if r["removed_examples"]:
            L.append("Removed in re (first keys): %s" % ", ".join(r["removed_examples"]))
            L.append("")
        if not r["fields"]:
            L.append("No field differs among the %d common entries." % r["common"])
            continue
        L.append("| field | entries changed | % of common |")
        L.append("|---|---:|---:|")
        for f, n in sorted(r["fields"].items(), key=lambda kv: (-kv[1], kv[0])):
            L.append("| %s | %d | %.1f |" % (f, n, 100.0 * n / r["common"]))
    L.append("")
    return "\n".join(L) + "\n"
