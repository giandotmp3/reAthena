"""Legacy script constants (script_get_constant) and compile-time limits, per server mode.

data/legacy_constants.json is generated by tools/extract_constants.py from the legacy dump hook (constants.tsv and
limits.tsv of a pre-renewal and a renewal build), so the names/values are exactly those of the real server.
Lookups are case-insensitive like the legacy constant hash.
"""
import json
import os

_HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(os.path.dirname(_HERE), "data", "legacy_constants.json")

# battle.conf values the loaders read; defaults of the shipped conf/battle/*.conf (verified by the dump hook).
BATTLE_DEFAULTS = {
    "base_exp_rate": 100, "job_exp_rate": 100, "mvp_exp_rate": 100,
    "monster_damage_delay_rate": 100, "view_range_rate": 100, "chase_range_rate": 100,
    "monster_active_enable": 1, "mvp_hp_rate": 100, "monster_hp_rate": 100,
    "display_hallucination": 1, "defnotenemy": 0, "area_size": 14, "use_statpoint_table": 1,
}


class Consts(object):
    def __init__(self, mode, table):
        self.mode = mode
        self.names = table["constants"]          # name -> value (definition order)
        self.limits = table["limits"]
        self._lower = {}
        for k, v in self.names.items():
            self._lower.setdefault(k.lower(), v)
        self._lim_lower = dict((k.lower(), v) for k, v in self.limits.items() if "." not in k)
        self._rev = {}                           # prefix -> {value: name-without-prefix} (first definition wins)
        self.battle = dict(BATTLE_DEFAULTS)
        for k in BATTLE_DEFAULTS:
            lim = self.limits.get("battle_config." + k)
            if lim is not None:
                self.battle[k] = lim

    def get(self, name):
        """script_get_constant (case-insensitive). Enum values that exist only in C (not exported to scripts) are looked
        up in the limits table, which the dump hook fills for the ones the loaders compare against."""
        v = self._lower.get(name.lower())
        if v is None:
            v = self._lim_lower.get(name.lower())
        return v

    def lim(self, name):
        return self.limits[name]

    def reverse(self, prefix):
        r = self._rev.get(prefix)
        if r is None:
            r = {}
            pl = len(prefix)
            for k, v in self.names.items():
                if k.startswith(prefix) and v not in r:
                    r[v] = k[pl:]
            self._rev[prefix] = r
        return r

    def name_of(self, prefix, value):
        return self.reverse(prefix).get(value)

    def bit_names(self, prefix, mask, universe=None):
        """names (prefix stripped) of single-bit constants set in mask; returns (names, rest_mask)."""
        out = []
        rest = mask
        items = []
        for k, v in self.names.items():
            if k.startswith(prefix) and v > 0 and (v & (v - 1)) == 0:
                items.append((v, k[len(prefix):]))
        seen = set()
        for v, n in sorted(items):
            if v in seen:
                continue
            seen.add(v)
            if mask & v:
                out.append(n)
                rest &= ~v
        return out, rest


_CACHE = {}


def load(mode, path=None):
    key = (mode, path)
    if key not in _CACHE:
        with open(path or DATA, "r") as f:
            data = json.load(f)
        _CACHE[key] = Consts(mode, data[mode])
    return _CACHE[key]
