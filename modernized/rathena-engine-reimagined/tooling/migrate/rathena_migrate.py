#!/usr/bin/env python3
"""rathena-migrate: legacy YAML databases -> Luau data modules.

    rathena_migrate.py migrate --mode prerenewal|renewal|both [--root REPO] [--out DIR] [--import-dir DIR]
    rathena_migrate.py validate --mode prerenewal|renewal|both [--root REPO] [--import-dir DIR]
    rathena_migrate.py diff [--root REPO] [--out DIR]

See README.md. The merge follows the legacy loader exactly (src/common/database.cpp + each parseBodyNode): header
checks, Header.Clear, Body entries in file order, Footer.Imports with Mode/Generator, per-field last-wins patching of an
existing Id, Index list patching, loader post-processing (loadingFinished). Nothing is written next to the YAML sources.
"""
import argparse
import hashlib
import json
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from rmig import __version__, pipeline, luau, emit as emitmod, diffreport  # noqa: E402

DEFAULT_ROOT = os.path.abspath(os.path.join(HERE, "..", "..", "..", ".."))
DEFAULT_OUT = os.path.join(HERE, "out")
HEADER = ["Generated by rathena-migrate %s from the legacy YAML databases (mode: %s). DO NOT EDIT.",
          "Entry ids are namespaced strings; client_id is the legacy numeric id. Scripts are rAthena script text (script_lang)."]


def sha(data):
    return hashlib.sha256(data).hexdigest()


def write(path, text, manifest_files, base):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    data = text.encode("utf-8", "surrogateescape")
    with open(path, "wb") as f:
        f.write(data)
    manifest_files[os.path.relpath(path, base)] = {"bytes": len(data), "sha256": sha(data)}


def validation_summary(loaded):
    out = {}
    for name in sorted(loaded.dbs):
        a = loaded.dbs[name]
        out[name] = {"files": a.files, "entries_parsed": a.parsed, "entries_rejected": len(a.rejected),
                     "rejects_by_reason": _count(a.rejected), "warnings": len(a.r.warnings), "missing_optional_files": a.missing,
                     "file_errors": a.file_errors, "clears": a.clears}
    return out


def _count(rej):
    d = {}
    for f, r in rej:
        d[r] = d.get(r, 0) + 1
    return dict(sorted(d.items()))


def migrate_mode(args, mode):
    t0 = time.time()
    loaded = pipeline.load_mode(args.root, mode, import_dir=args.import_dir, renewal_aspd=not args.no_renewal_aspd,
                                raw=not args.no_raw, generator=args.generator)
    t_load = time.time() - t0
    outdir = os.path.join(args.out, mode)
    em = emitmod.Emitter(loaded, mode)
    files = {}
    hdr = [HEADER[0] % (__version__, mode), HEADER[1]]
    counts = {}

    def put(name, entries, sub=""):
        notes = []
        text = luau.module(hdr, entries, notes)
        write(os.path.join(outdir, sub, name + ".luau"), text, files, outdir)
        counts[(sub + "/" if sub else "") + name] = len(entries)
        for n in notes[:3]:
            em.notes.append("%s: %s" % (name, n))

    items = em.items()
    for cat in ("usable", "equip", "etc"):
        put("item_db_" + cat, items[cat])
    put("mob_db", em.mobs())
    put("skill_db", em.skills())
    put("status", em.statuses())
    for k, v in em.jobs_tables().items():
        put(k, v)
    put("size_fix", em.size_fix())
    put("attr_fix", em.attr_fix())
    put("refine", em.refine())
    put("statpoint", em.statpoint())
    raw_names = []
    if not args.no_raw:
        for name in sorted(n for n in loaded.dbs if n in emitmod_raw_names()):
            if not loaded.dbs[name].rows:
                continue
            put(name, em.raw(name), "raw")
            raw_names.append(name)
    val = validation_summary(loaded)
    manifest = {
        "tool": "rathena-migrate", "version": __version__, "mode": mode, "root": "(repo root)",
        "import_dir": args.import_dir, "renewal_aspd": not args.no_renewal_aspd,
        "entries": {
            "item": len(loaded.dbs["item_db"].rows), "mob": len(loaded.dbs["mob_db"].rows),
            "skill": len(loaded.dbs["skill_db"].rows), "status": len(loaded.dbs["status"].rows),
            "job": len(loaded.dbs["job_stats"].rows)},
        "module_entry_counts": dict(sorted(counts.items())),
        "raw_tables_todo": raw_names,
        "id_slug_collisions": [list(map(str, c)) for c in em.ids.collisions],
        "emit_notes": sorted(set(em.notes))[:50],
        "validation": val,
        "files": dict(sorted(files.items())),
    }
    write(os.path.join(outdir, "manifest.json"), json.dumps(manifest, indent=1, sort_keys=True) + "\n", files, outdir)
    return loaded, manifest, t_load, time.time() - t0


def emitmod_raw_names():
    from rmig.db_raw import RAW_DBS
    return RAW_DBS


def fatal_problems(manifest):
    errs = []
    for db, v in manifest["validation"].items():
        for f, m in v["file_errors"]:
            errs.append("%s: %s: %s" % (db, f, m))
    return errs


def main(argv=None):
    ap = argparse.ArgumentParser(prog="rathena_migrate", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    for name in ("migrate", "validate", "diff"):
        p = sub.add_parser(name)
        p.add_argument("--root", default=DEFAULT_ROOT, help="repository root holding db/ (default: this repo)")
        p.add_argument("--out", default=DEFAULT_OUT, help="output directory (default: tooling/migrate/out)")
        p.add_argument("--import-dir", default="db/import", help="directory used for the 'db/import/' overlay chain (relative to --root or absolute)")
        p.add_argument("--no-raw", action="store_true", help="skip the not-yet-ported raw tables (quests, pets, ...)")
        p.add_argument("--no-renewal-aspd", action="store_true", help="renewal mode with RENEWAL_ASPD off: job_aspd comes from db/pre-re")
        p.add_argument("--generator", action="store_true", help="also follow imports marked Generator: true")
        p.add_argument("--only", help="comma separated DB names to load (validate only; dependencies are added): item_db,skill_db,mob_db,status,job_stats,statpoint,size_fix,refine,attr_fix")
        p.add_argument("--strict", action="store_true", help="exit 1 when any entry is rejected or any warning of class 'reject' occurred")
        if name != "diff":
            p.add_argument("--mode", choices=["prerenewal", "renewal", "both"], default="both")
    args = ap.parse_args(argv)
    if args.cmd == "diff":
        args.mode = "both"
    modes = ["prerenewal", "renewal"] if args.mode == "both" else [args.mode]
    results = {}
    rc = 0
    for m in modes:
        if args.cmd == "validate":
            t0 = time.time()
            only = set(args.only.split(",")) if args.only else None
            L = pipeline.load_mode(args.root, m, import_dir=args.import_dir, renewal_aspd=not args.no_renewal_aspd,
                                   raw=not args.no_raw, generator=args.generator, only=only)
            val = validation_summary(L)
            print(json.dumps({"mode": m, "validation": val}, indent=1, sort_keys=True))
            errs = [("%s: %s: %s" % (db, f, msg)) for db, v in val.items() for f, msg in v["file_errors"]]
            rej = sum(v["entries_rejected"] for v in val.values())
            results[m] = L
            if errs:
                rc = 2
            elif args.strict and rej:
                rc = 1
            print("%s: validated in %.1fs (%d rejected entries)" % (m, time.time() - t0, rej), file=sys.stderr)
            continue
        if args.cmd == "diff":
            L = pipeline.load_mode(args.root, m, import_dir=args.import_dir, renewal_aspd=not args.no_renewal_aspd,
                                   raw=not args.no_raw, generator=args.generator)
            results[m] = L
            continue
        L, manifest, tl, tt = migrate_mode(args, m)
        results[m] = L
        errs = fatal_problems(manifest)
        print("%-10s items=%d mobs=%d skills=%d statuses=%d jobs=%d  load=%.1fs total=%.1fs  rejected=%d" % (
            m, manifest["entries"]["item"], manifest["entries"]["mob"], manifest["entries"]["skill"],
            manifest["entries"]["status"], manifest["entries"]["job"], tl, tt,
            sum(v["entries_rejected"] for v in manifest["validation"].values())))
        for e in errs:
            print("ERROR:", e, file=sys.stderr)
        if errs:
            rc = 2
        elif args.strict and sum(v["entries_rejected"] for v in manifest["validation"].values()):
            rc = 1
    if args.cmd in ("migrate", "diff") and len(modes) == 2:
        rows = diffreport.build(results["prerenewal"], results["renewal"], raw_dbs=[] if args.no_raw else sorted(emitmod_raw_names()))
        text = diffreport.render(rows, {"version": __version__})
        path = os.path.join(args.out, "diff_pre_vs_re.md")
        os.makedirs(args.out, exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
        print("wrote", path)
    return rc


if __name__ == "__main__":
    sys.exit(main())
