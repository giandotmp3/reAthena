#!/usr/bin/env python3
"""Run the whole legacy-equivalence verification: for both modes and three scenarios (base = shipped data, patch =
tests/fixtures/overlay_patch, clear = tests/fixtures/overlay_clear) dump the real legacy loader's state and compare it with
the migrator field by field. Writes out/verification/*.json and out/verification_report.md.

    verify_all.py --pre-build <dir from build_dump.sh with RA_PRERENEWAL=1> --re-build <dir from build_dump.sh> [--work DIR]
"""
import argparse
import json
import os
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
MIG = os.path.dirname(HERE)
FIX = os.path.join(MIG, "tests", "fixtures")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pre-build", required=True)
    ap.add_argument("--re-build", required=True)
    ap.add_argument("--work", default=os.path.join(MIG, "out", "verification", "dumps"))
    ap.add_argument("--out", default=os.path.join(MIG, "out"))
    a = ap.parse_args()
    os.makedirs(os.path.join(a.out, "verification"), exist_ok=True)
    results = []
    t0 = time.time()
    for mode, build in (("prerenewal", a.pre_build), ("renewal", a.re_build)):
        for scen in ("base", "patch", "clear"):
            dump = os.path.join(a.work, "%s_%s" % (mode, scen))
            cmd = [os.path.join(MIG, "legacy_dump", "run_dump.sh"), build, dump]
            imp = "db/import"
            if scen != "base":
                cmd.append(os.path.join(FIX, "overlay_" + scen))
                imp = os.path.join(FIX, "overlay_" + scen)
            subprocess.run(cmd, check=True, stdout=subprocess.DEVNULL)
            js = os.path.join(a.out, "verification", "%s_%s.json" % (mode, scen))
            p = subprocess.run([sys.executable, "-I", os.path.join(HERE, "compare_legacy.py"), "--mode", mode, "--dump", dump,
                                "--import-dir", imp, "--json", js], capture_output=True, text=True)
            results.append((mode, scen, p.returncode, json.load(open(js))))
            print("%s/%s: rc=%d" % (mode, scen, p.returncode), flush=True)
    L = ["# Legacy-loader equivalence report", "",
         "Generated by `tools/verify_all.py`. The legacy server is the real map-server built from a COPY of this tree with the dump hook "
         "(`legacy_dump/`), run headless after full DB load. `identical entries` = every dumped field of the entry equals the migrator's "
         "merged value. Scenario `base` = shipped data, `patch` = `tests/fixtures/overlay_patch/*` as `db/import`, `clear` = "
         "`tests/fixtures/overlay_clear/*` (Header.Clear).", ""]
    for mode, scen, rc, rep in results:
        L.append("## %s / %s%s" % (mode, scen, "" if rc == 0 else "  (UNEXPLAINED MISMATCHES)"))
        L.append("")
        L.append("| DB | legacy entries | migrator entries | only legacy | only migrator | identical entries | field checks | field matches | explained diffs |")
        L.append("|---|---:|---:|---:|---:|---:|---:|---:|---|")
        for d in rep["dbs"]:
            ex = "; ".join("%s x%d (%s)" % (f, e["count"], e["class"]) for f, e in sorted(d["explained"].items())) or "-"
            L.append("| %s | %d | %d | %d | %d | %d / %d | %d | %d | %s |" % (
                d["db"], d["legacy_entries"], d["migrator_entries"], d["only_in_legacy_count"], d["only_in_migrator_count"],
                d["entries_identical"], d["common"], d["field_checks"], d["field_matches"], ex))
            for f, e in sorted(d["mismatched_fields"].items()):
                L.append("|  | UNEXPLAINED %s x%d | | | | | | | |" % (f, e["count"]))
        L.append("")
    notes = {}
    for _, _, _, rep in results:
        for d in rep["dbs"]:
            for f, e in d["explained"].items():
                notes[(d["db"], f)] = (e["class"], e["note"])
    L.append("## Explained difference classes")
    L.append("")
    for (db, f), (cls, note) in sorted(notes.items()):
        L.append("* `%s.%s` [%s]: %s" % (db, f, cls, note))
    L.append("")
    path = os.path.join(a.out, "verification_report.md")
    with open(path, "w") as f:
        f.write("\n".join(L) + "\n")
    print("wrote", path, "in %.0fs" % (time.time() - t0))
    return 0 if all(rc == 0 for _, _, rc, _ in results) else 1


if __name__ == "__main__":
    sys.exit(main())
