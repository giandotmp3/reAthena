#!/usr/bin/env python3
"""Build data/legacy_constants.json from two legacy dump directories (constants.tsv + limits.tsv written by the
dump hook in legacy_dump/). The constants are the real script constants of the server build, so the migrator never
guesses an enum value.

    extract_constants.py --prerenewal <dump-dir> --renewal <dump-dir> [--out data/legacy_constants.json]
"""
import argparse
import json
import os

PREFIXES = ("IT_", "W_", "AMMO_", "CARD_", "SEX_", "EQP_", "DROPEFFECT_", "SC_", "EFST_", "ITEMJ_", "EAJ_", "RC_", "RC2_",
            "ELE_", "MONSTER_TYPE_", "MD_", "CLASS_", "Size_", "SZ_", "JOB_", "PARAM_", "BF_", "INF_", "INF2_", "NK_",
            "DMG_", "SKILL_", "ST_", "UNT_", "BCT_", "UF_", "BL_", "SCS_", "SCB_", "OPT1_", "OPT2_", "OPT3_", "OPTION_",
            "SCF_", "REFINE_", "RDMOPT_")


PREFIXES_UP = tuple(p.upper() for p in PREFIXES)   # script constants are case-insensitive (Job_SuperNovice == JOB_SUPERNOVICE)


def read(d):
    consts = {}
    with open(os.path.join(d, "constants.tsv"), "r", encoding="latin-1") as f:
        for line in f:
            line = line.rstrip("\n")
            if "\t" not in line:
                continue
            k, v = line.split("\t", 1)
            if k.upper().startswith(PREFIXES_UP) and k not in consts:
                consts[k] = int(v)
    limits = {}
    with open(os.path.join(d, "limits.tsv"), "r") as f:
        for line in f:
            line = line.rstrip("\n")
            if "\t" in line:
                k, v = line.split("\t", 1)
                limits[k] = int(v)
    return {"constants": consts, "limits": limits}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--prerenewal", required=True)
    ap.add_argument("--renewal", required=True)
    ap.add_argument("--out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "data", "legacy_constants.json"))
    a = ap.parse_args()
    data = {"_provenance": "generated by tools/extract_constants.py from the legacy dump hook (script constants + limits.tsv)",
            "prerenewal": read(a.prerenewal), "renewal": read(a.renewal)}
    with open(a.out, "w") as f:
        json.dump(data, f, indent=0, sort_keys=False, separators=(",", ":"))
        f.write("\n")
    for m in ("prerenewal", "renewal"):
        print(m, len(data[m]["constants"]), "constants", len(data[m]["limits"]), "limits")


if __name__ == "__main__":
    main()
