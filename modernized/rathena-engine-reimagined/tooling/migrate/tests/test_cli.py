def mini_repo(extra_import_files):
    """A repo root whose db/ is a view onto the real one (symlinks) with a private db/import."""
    root = tempfile.mkdtemp(prefix="rmig-root-")
    os.makedirs(os.path.join(root, "db", "import"))
    for name in os.listdir(os.path.join(REPO, "db")):
        if name in ("import",):
            continue
        os.symlink(os.path.join(REPO, "db", name), os.path.join(root, "db", name))
    for name, text in extra_import_files.items():
        with open(os.path.join(root, "db", "import", name), "w") as f:
            f.write(text)
    return root


def run_cli(argv):
    out, err = io.StringIO(), io.StringIO()
    with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
        try:
            rc = rathena_migrate.main(argv)
        except SystemExit as e:
            rc = e.code
    return rc, out.getvalue(), err.getvalue()


class MalformedInputTests(unittest.TestCase):
    def tearDown(self):
        for r in getattr(self, "roots", []):
            shutil.rmtree(r, ignore_errors=True)

    def root(self, files):
        r = mini_repo(files)
        self.roots = getattr(self, "roots", []) + [r]
        return r

    def validate(self, files, *extra):
        r = self.root(files)
        return run_cli(["validate", "--root", r, "--mode", "prerenewal", "--only", "item_db", "--no-raw"] + list(extra))

    def test_clean_overlay_passes(self):
        good = "Header:\n  Type: ITEM_DB\n  Version: 3\nBody:\n  - Id: 501\n    Weight: 1\n"
        rc, out, err = self.validate({"item_db.yml": good})
        self.assertEqual(rc, 0, err)

    def test_yaml_syntax_error_is_fatal(self):
        rc, out, err = self.validate({"item_db.yml": "Header: [oops\n"})
        self.assertEqual(rc, 2)
        data = json.loads(out)
        self.assertIn("syntax", data["validation"]["item_db"]["file_errors"][0][1])

    def test_wrong_header_type_and_future_version_are_fatal(self):
        rc, out, _ = self.validate({"item_db.yml": "Header:\n  Type: MOB_DB\n  Version: 3\n"})
        self.assertEqual(rc, 2)
        rc, out, _ = self.validate({"item_db.yml": "Header:\n  Type: ITEM_DB\n  Version: 9\n"})
        self.assertEqual(rc, 2)
        rc, out, _ = self.validate({"item_db.yml": "Body:\n  - Id: 1\n"})
        self.assertEqual(rc, 2)

    def test_rejected_entries_are_reported_and_strict_fails(self):
        bad = "Header:\n  Type: ITEM_DB\n  Version: 3\nBody:\n  - Id: 501\n    Weight: heavy\n  - Id: 9999\n    Name: NoAegis\n"
        rc, out, err = self.validate({"item_db.yml": bad})
        self.assertEqual(rc, 0)
        data = json.loads(out)
        self.assertEqual(data["validation"]["item_db"]["entries_rejected"], 2)
        rc, out, err = self.validate({"item_db.yml": bad}, "--strict")
        self.assertEqual(rc, 1)

    def test_unknown_mode_is_rejected_by_the_cli(self):
        rc, out, err = run_cli(["validate", "--mode", "bogus"])
        self.assertEqual(rc, 2)

    def test_nothing_is_written_next_to_the_yaml(self):
        r = self.root({})
        before = file_hashes(os.path.join(r, "db", "import"))
        self.validate({})
        self.assertEqual(file_hashes(os.path.join(r, "db", "import")), before)


