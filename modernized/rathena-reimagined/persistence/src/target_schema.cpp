/// Logical column types, mapped per dialect. Integers that legacy stores as UNSIGNED INT go to
/// BIGINT on PostgreSQL (no unsigned types there); SQLite INTEGER is 64-bit. Identity is a
/// generated BIGINT primary key (SQLite: INTEGER PRIMARY KEY AUTOINCREMENT).
enum class Type { Int, BigInt, Text, Blob, Identity };

struct Column {
	std::string_view name;
	Type type;
	std::string_view constraints; ///< dialect-neutral: NOT NULL, DEFAULT, CHECK with lower()/length()
};

struct Table {
	std::string_view logical;                   ///< TableNames field (resolve_table())
	std::vector<Column> columns;
	std::vector<std::string_view> primary_key; ///< composite key; empty with an Identity column
	std::string extra;                          ///< further table constraints (UNIQUE, CHECK)
	std::int64_t identity_start = 1;            ///< first generated id of the Identity column
};

std::string type_sql(Type t, SqlDialect d, std::int64_t identity_start) {
	switch (t) {
	case Type::Int: return "INTEGER";
	case Type::BigInt: return d == SqlDialect::Postgres ? "BIGINT" : "INTEGER";
	case Type::Text: return "TEXT";
	case Type::Blob: return d == SqlDialect::Postgres ? "BYTEA" : "BLOB";
	case Type::Identity:
		// AUTOINCREMENT: SQLite never reuses the id of a deleted row (the legacy servers expect that
		// of char_id, mail id, ...); the start is seeded into sqlite_sequence.
		return d == SqlDialect::Postgres
		           ? "BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH " + std::to_string(identity_start) + ") PRIMARY KEY"
		           : "INTEGER NOT NULL PRIMARY KEY AUTOINCREMENT";
	}
	return "TEXT";
}

std::string_view on_delete_sql(OnDelete a) {
	switch (a) {
	case OnDelete::Cascade: return "CASCADE";
	case OnDelete::SetNull: return "SET NULL";
	case OnDelete::Restrict: return "RESTRICT";
	}
	return "RESTRICT";
}

/// Item value columns of one item table, from the ONE mapping (item_columns()).
std::vector<Column> item_value_columns(ItemTable t) {
	static const std::vector<std::string> names[] = {
	    item_columns(ItemTable::Inventory), item_columns(ItemTable::Cart), item_columns(ItemTable::Storage),
	    item_columns(ItemTable::GuildStorage), item_columns(ItemTable::MailAttachments)};
	std::vector<Column> cols;
	for (const auto& n : names[static_cast<std::size_t>(t)]) cols.push_back({n, Type::BigInt, "NOT NULL DEFAULT 0"});
	return cols;
}

std::vector<Column> with(std::vector<Column> head, const std::vector<Column>& tail) {
	head.insert(head.end(), tail.begin(), tail.end());
	return head;
}

