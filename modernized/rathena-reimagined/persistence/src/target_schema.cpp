std::string foreign_key_clause(SqlDialect d, const TableNames& names, const ForeignKeySpec& fk) {
	auto q = [d](std::string_view n) { return quote_identifier(n, d); };
	return "FOREIGN KEY (" + q(fk.column) + ") REFERENCES " + q(resolve_table(names, fk.parent_table)) + " (" +
	       q(fk.parent_column) + ") ON DELETE " + std::string(on_delete_sql(fk.on_delete));
}

