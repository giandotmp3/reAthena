std::vector<Statement> target_schema_statements(SqlDialect d, const TableNames& names) {
	auto q = [d](std::string_view n) { return quote_identifier(n, d); };
	std::vector<Statement> out;
	std::vector<Statement> indexes;
	std::vector<Statement> deferred; // PostgreSQL: foreign keys to a table created further down
	std::set<std::string_view> created;

	for (const auto& table : tables()) {
		const std::string name(resolve_table(names, table.logical));
		std::string sql = "CREATE TABLE IF NOT EXISTS " + q(name) + " (";
		bool first = true;
		std::string_view identity;
		for (const auto& c : table.columns) {
			sql += (first ? "\n  " : ",\n  ") + q(c.name) + " " + type_sql(c.type, d, table.identity_start);
			if (!c.constraints.empty()) sql += " " + std::string(c.constraints);
			if (c.type == Type::Identity) identity = c.name;
			first = false;
		}
		if (!table.primary_key.empty()) {
			std::string pk;
			for (const auto c : table.primary_key) pk += (pk.empty() ? "" : ", ") + q(c);
			sql += ",\n  PRIMARY KEY (" + pk + ")";
		}
		if (!table.extra.empty()) sql += ",\n  " + table.extra;
		created.insert(table.logical);
		for (const auto& fk : target_foreign_keys()) {
			if (fk.child_table != table.logical) continue;
			// SQLite resolves a reference when a row is written, so a later table is fine there;
			// PostgreSQL needs the parent to exist (char.guild_id -> guild is the one forward one).
			if (d == SqlDialect::Postgres && !created.contains(fk.parent_table)) {
				const std::string constraint = name + "_" + std::string(fk.column) + "_fkey";
				deferred.push_back({"DO $$ BEGIN ALTER TABLE " + q(name) + " ADD CONSTRAINT " + q(constraint) + " " +
				                        foreign_key_clause(d, names, fk) +
				                        "; EXCEPTION WHEN duplicate_object THEN NULL; END $$",
				                    {}});
			} else {
				sql += ",\n  " + foreign_key_clause(d, names, fk);
			}
			// Index the referencing column (cascades and lookups by owner) unless a key leads with it.
			const bool leads = fk.column == identity || (!table.primary_key.empty() && table.primary_key.front() == fk.column);
			if (!leads)
				indexes.push_back({"CREATE INDEX IF NOT EXISTS " + q(name + "_" + std::string(fk.column)) + " ON " + q(name) +
				                       " (" + q(fk.column) + ")",
				                   {}});
		}
		sql += "\n)";
		if (d == SqlDialect::Sqlite) sql += " STRICT"; // reject values of the wrong type
		out.push_back({std::move(sql), {}});
		if (d == SqlDialect::Sqlite && !identity.empty() && table.identity_start > 1) {
			// First generated id (e.g. char_id 150000, START_CHAR_NUM); only on a fresh table.
			out.push_back({"INSERT INTO \"sqlite_sequence\" (\"name\", \"seq\") SELECT ?, ? WHERE NOT EXISTS (SELECT 1 FROM "
			               "\"sqlite_sequence\" WHERE \"name\" = ?)",
			               {name, std::int64_t{table.identity_start - 1}, name}});
		}
		if (table.logical == "login") {
			// BR-LOGIN-038 case-insensitive lookups use lower(userid); keep them indexed.
			out.push_back({"CREATE INDEX IF NOT EXISTS " + q(name + "_userid_lower") + " ON " + q(name) + " (lower(" +
			                   q("userid") + "))",
			               {}});
		}
	}
	out.insert(out.end(), deferred.begin(), deferred.end());
	out.insert(out.end(), indexes.begin(), indexes.end());
	return out;
}

bool create_target_schema(SqlConnection& conn, const TableNames& names) {
	auto statements = target_schema_statements(conn.dialect(), names);
	const auto d = conn.dialect();
	auto q = [d](std::string_view n) { return quote_identifier(n, d); };
	// The application clock is not available here; the schema creation time is informational.
	const std::string now = d == SqlDialect::Postgres ? "CAST(EXTRACT(EPOCH FROM now()) AS BIGINT)" : "CAST(strftime('%s', 'now') AS INTEGER)";
	statements.push_back({"INSERT INTO " + q(names.schema_migrations) + " (" + q("version") + ", " + q("applied_at") +
	                          ") VALUES (?, " + now + ") ON CONFLICT (" + q("version") + ") DO NOTHING",
	                      {std::string(kTargetSchemaVersion)}});
	return conn.execute_in_transaction(statements);
}

